export const riderDeliveryTransitions: Record<string, readonly string[]> = {
  ASSIGNED: ['PREPARING_DISPATCH', 'IN_TRANSIT', 'DELIVERY_FAILED', 'CANCELLATION_REQUESTED'],
  PREPARING_DISPATCH: ['IN_TRANSIT', 'DELIVERY_FAILED', 'CANCELLATION_REQUESTED'],
  IN_TRANSIT: ['DELIVERY_FAILED', 'CANCELLATION_REQUESTED', 'RETURN_REQUESTED'],
  DELIVERY_FAILED: ['IN_TRANSIT', 'RETURN_REQUESTED'],
}

export function riderDeliveryNeedsReason(status: string) {
  return ['DELIVERY_FAILED', 'CANCELLATION_REQUESTED', 'RETURN_REQUESTED'].includes(status)
}
